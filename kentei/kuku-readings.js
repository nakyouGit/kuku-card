/**
 * kuku-readings.js
 * 九九の読み方データ（教室掲示の九九表に合わせた表記）。
 * 九九検定ゲーム本体とマイクテストの両方から使う。
 */
(function (global) {
  'use strict';

  const MIN_NUMBER = 1;
  const MAX_NUMBER = 9;

  // READINGS[段][かける数 - 1]
  const READINGS = {
    1: ['いんいちがいち', 'いんにがに', 'いんさんがさん', 'いんしがし', 'いんごがご',
        'いんろくがろく', 'いんしちがしち', 'いんはちがはち', 'いんくがく'],
    2: ['にいちがに', 'ににんがし', 'にさんがろく', 'にしがはち', 'にごじゅう',
        'にろくじゅうに', 'にしちじゅうし', 'にはちじゅうろく', 'にくじゅうはち'],
    3: ['さんいちがさん', 'さんにがろく', 'さざんがく', 'さんしじゅうに', 'さんごじゅうご',
        'さぶろくじゅうはち', 'さんしちにじゅういち', 'さんぱにじゅうし', 'さんくにじゅうしち'],
    4: ['しいちがし', 'しにがはち', 'しさんじゅうに', 'ししじゅうろく', 'しごにじゅう',
        'しろくにじゅうし', 'ししちにじゅうはち', 'しはさんじゅうに', 'しくさんじゅうろく'],
    5: ['ごいちがご', 'ごにじゅう', 'ごさんじゅうご', 'ごしにじゅう', 'ごごにじゅうご',
        'ごろくさんじゅう', 'ごしちさんじゅうご', 'ごはしじゅう', 'ごっくしじゅうご'],
    6: ['ろくいちがろく', 'ろくにじゅうに', 'ろくさんじゅうはち', 'ろくしにじゅうし', 'ろくごさんじゅう',
        'ろくろくさんじゅうろく', 'ろくしちしじゅうに', 'ろくはしじゅうはち', 'ろっくごじゅうし'],
    7: ['しちいちがしち', 'しちにじゅうし', 'しちさんにじゅういち', 'しちしにじゅうはち', 'しちごさんじゅうご',
        'しちろくしじゅうに', 'しちしちしじゅうく', 'しちはごじゅうろく', 'しちくろくじゅうさん'],
    8: ['はちいちがはち', 'はちにじゅうろく', 'はちさんにじゅうし', 'はちしさんじゅうに', 'はちごしじゅう',
        'はちろくしじゅうはち', 'はちしちごじゅうろく', 'はっぱろくじゅうし', 'はっくしちじゅうに'],
    9: ['くいちがく', 'くにじゅうはち', 'くさんにじゅうしち', 'くしさんじゅうろく', 'くごしじゅうご',
        'くろくごじゅうし', 'くしちろくじゅうさん', 'くはしちじゅうに', 'くくはちじゅういち'],
  };

  Object.keys(READINGS).forEach((dan) => Object.freeze(READINGS[dan]));
  Object.freeze(READINGS);

  function isValidNumber(n) {
    return Number.isInteger(n) && n >= MIN_NUMBER && n <= MAX_NUMBER;
  }

  /** 段 a・かける数 b の読み方を返す。範囲外は例外にする。 */
  function getReading(a, b) {
    if (!isValidNumber(a) || !isValidNumber(b)) {
      throw new RangeError(`九九の範囲外です: ${a}×${b}`);
    }
    return READINGS[a][b - 1];
  }

  global.KukuReadings = Object.freeze({
    MIN_NUMBER,
    MAX_NUMBER,
    READINGS,
    isValidNumber,
    getReading,
  });
})(window);
